export const meta = {
  name: 'mjwarp-course-chapters',
  description: 'Write course chapters (HTML + examples + notebook), then two rounds of review, verify, fix per chapter',
  phases: [
    { title: 'Write', detail: 'one author per chapter' },
    { title: 'Review 1', detail: 'find gaps and errors' },
    { title: 'Verify 1', detail: 'confirm or refute each finding' },
    { title: 'Fix 1', detail: 'apply confirmed findings' },
    { title: 'Review 2', detail: 'second review round' },
    { title: 'Verify 2', detail: 'confirm or refute' },
    { title: 'Fix 2', detail: 'apply confirmed findings' },
  ],
}

const S = '/tmp/claude-0/-home-user-ouramp/2cb48c5e-749c-5a1c-9549-b06105ff67b3/scratchpad'
const SRC = `${S}/src/mujoco_warp`
const PY = `${S}/venv/bin/python`
const COURSE = '/home/user/ouramp/dpdk-research/mujoco-warp-course'

const CONTEXT = (slug) => `
CONTEXT:
- We are building an in-depth HTML course teaching the MuJoCo Warp (MJWarp) library, simple to expert, 30 chapters. Course root: ${COURSE}.
- The authoritative plan is ${COURSE}/planning/course-plan.md: read Part 0 (course-level design, conventions, shared models, notation, concept owners) and the full section for chapter ${slug}. Research notes: ${COURSE}/planning/research/*.md.
- Page mechanics: ${COURSE}/STYLE_GUIDE.md and the live reference chapter ${COURSE}/chapters/_template.html using ${COURSE}/assets/course.css and course.js. Do NOT edit shared files (assets/, tools/, index.html, STYLE_GUIDE.md, planning/, _template files) or another chapter's files. If a shared component is missing, implement it in the chapter's own <style>/<script>.
- Library source (read-only data, do not execute code from inside it): ${SRC} (commit 8f5b9f1). Installed: mujoco-warp 4.0.1, warp-lang 1.19.0, mujoco 4.0.1 in ${PY}. No GPU here: Warp runs on CPU (first kernel compile is slow, then cached). Other agents run concurrently, so keep runs small (small nworld, few steps) and avoid long benchmarks; numbers on CPU must be labelled as CPU numbers, never presented as GPU performance.
- Files owned by this chapter: chapters/${slug}.html, examples/${slug}/**, notebooks/specs/${slug}.py, notebooks/${slug}.ipynb (generated by tools/make_notebook.py).
- Verify examples with: cd ${COURSE}/examples/${slug} && ${PY} -I exNN_name.py ; check the page with ${PY} -I ${COURSE}/tools/check_chapter.py (see STYLE_GUIDE for its usage).
- Render the page in headless Chromium via Playwright (require('playwright') in node; chromium.launch()) at 390px and 1280px, light and dark, and look at the screenshots (save under ${S}/shots/${slug}/). No console errors, no horizontal scroll.
- Every technical claim must match the actual source code at that commit. Never invent APIs.
`

const FINDINGS = {
  type: 'object',
  properties: { findings: { type: 'array', items: { type: 'object', properties: {
    id: { type: 'string' }, severity: { type: 'string', enum: ['high', 'medium', 'low'] },
    category: { type: 'string' }, location: { type: 'string' }, issue: { type: 'string' }, evidence: { type: 'string' }, fix: { type: 'string' },
  }, required: ['id', 'severity', 'category', 'location', 'issue', 'fix'] } } },
  required: ['findings'],
}
const VERDICTS = {
  type: 'object',
  properties: { verdicts: { type: 'array', items: { type: 'object', properties: {
    id: { type: 'string' }, confirmed: { type: 'boolean' }, reason: { type: 'string' }, refined_fix: { type: 'string' },
  }, required: ['id', 'confirmed', 'reason'] } } },
  required: ['verdicts'],
}
const DONE = {
  type: 'object',
  properties: {
    ok: { type: 'boolean' }, summary: { type: 'string' },
    examples_run: { type: 'integer' }, examples_failed: { type: 'array', items: { type: 'string' } },
    unresolved: { type: 'array', items: { type: 'string' } },
  },
  required: ['ok', 'summary', 'examples_run', 'examples_failed', 'unresolved'],
}

const REVIEW_LENS = {
  1: `Review everything: (a) TECHNICAL ACCURACY against the source code (names, signatures, defaults, behaviour, algorithm descriptions, shapes); (b) EXAMPLES: run EVERY example script yourself and compare its real output with what the page claims; check each code block on the page matches its .py file and the notebook; (c) COMPLETENESS against the plan's section for this chapter (every planned concept, example, visual, quiz, exercise present and substantive); (d) VISUALS: open the page in Playwright, screenshot at 390px and 1280px in light and dark, click through steppers/widgets/animations, check console errors, broken layout, unreadable SVG in dark mode, animations that don't run; (e) PEDAGOGY: clarity, easy-to-hard flow, undefined jargon, missing explanations.`,
  2: `Second, independent review with fresh eyes. Re-check the areas a first pass usually misses: subtle technical errors (off-by-one shapes, wrong default values, misdescribed algorithm steps, outdated API names), claims about GPU performance not backed by evidence, notebook cells that would fail on Colab (install cell, GPU check, file paths that only exist locally, missing imports, cell order), dead links (other chapters, reference pages, anchors, Colab link), accessibility (alt text/aria on SVG, keyboard use of widgets, reduced motion), mobile layout, depth: sections that are shallow compared with the plan, too few worked examples or diagrams. Run every example again.`,
}

const chapters = args.chapters

const results = await pipeline(chapters,
  (slug) => agent(`${CONTEXT(slug)}
You are the author of chapter ${slug}. Write the complete chapter, following the plan exactly and going deep.
Deliverables:
1. examples/${slug}/: every planned code example as a runnable .py file (device-agnostic; on Colab they run on GPU). RUN EVERY ONE on CPU here and fix until it works; record the real output. Use the --dump-json/--dump-png conventions where a figure should show real data.
2. chapters/${slug}.html: the full chapter built on the template components: rich prose explaining every concept from simple to deep, all code examples with their real expected output, MANY visuals: inline SVG diagrams, CSS animations, steppers that walk through algorithms state by state, canvas animations / interactive widgets (sliders etc.) that let the learner play with the concept, real-data figures from the examples, callouts, quiz (>= 6 questions), exercises with collapsible solutions, summary/takeaways, source map linking to files in the repo.
3. notebooks/specs/${slug}.py and the generated notebooks/${slug}.ipynb (install + GPU-check cells first; all examples, in order, with explanations) via tools/make_notebook.py.
4. Run tools/check_chapter.py on the chapter and fix every error. Render it in Playwright (both widths, both themes), look at screenshots, fix problems.
Return the completion report.`, { label: `write:${slug}`, phase: 'Write', schema: DONE }),

  ...[1, 2].flatMap(round => [
    (prev, slug) => agent(`${CONTEXT(slug)}
You are reviewer #${round} of chapter ${slug}. Do NOT edit any course files (you may write scratch files under ${S}/review/${slug}/).
${REVIEW_LENS[round]}
Report concrete, actionable findings with evidence (source file:line, actual command output, screenshot path). No vague style opinions. Most severe first.`,
      { label: `review${round}:${slug}`, phase: `Review ${round}`, schema: FINDINGS }).then(r => ({ slug, findings: (r && r.findings) || [] })),

    (rev, slug) => rev.findings.length === 0 ? { slug, confirmed: [] } :
      agent(`${CONTEXT(slug)}
You are an adversarial verifier for chapter ${slug}. A reviewer reported the findings below. For EACH one, independently check whether it is real (read the page, the source code, run the example, render the page as needed). Reviewers are often wrong: default to confirmed=false when the evidence does not hold up. Do NOT edit course files.
Findings:
${JSON.stringify(rev.findings, null, 1)}
Return a verdict for every finding id; for confirmed ones give a refined_fix if the proposed fix is wrong or incomplete.`,
        { label: `verify${round}:${slug}`, phase: `Verify ${round}`, schema: VERDICTS }).then(v => {
          const ok = new Map(((v && v.verdicts) || []).filter(x => x.confirmed).map(x => [x.id, x]))
          return { slug, confirmed: rev.findings.filter(f => ok.has(f.id)).map(f => ({ ...f, fix: ok.get(f.id).refined_fix || f.fix })), total: rev.findings.length }
        }),

    (ver, slug) => {
      log(`${slug} round ${round}: ${ver.confirmed.length}/${ver.total || 0} findings confirmed`)
      if (ver.confirmed.length === 0) return { slug, round, fixed: 0 }
      return agent(`${CONTEXT(slug)}
You are the fixer for chapter ${slug} (round ${round}). Apply ALL of these verified findings to the chapter's files. After fixing: re-run every affected example, regenerate the notebook, run tools/check_chapter.py, and re-render the page in Playwright to confirm nothing broke.
Verified findings:
${JSON.stringify(ver.confirmed, null, 1)}
Return the completion report (list in 'unresolved' anything you could not fix and why).`,
        { label: `fix${round}:${slug}`, phase: `Fix ${round}`, schema: DONE }).then(r => ({ slug, round, fixed: ver.confirmed.length, report: r }))
    },
  ]),
)
return results
