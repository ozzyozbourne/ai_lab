/* SPDX-License-Identifier: BSD-3-Clause
 * Chapter 11, step 5 (the final app): real options with rte_argparse and an
 * .ini configuration file with rte_cfgfile.
 *
 * Steps 1-4 parsed their few options with getopt_long() and hard-coded the
 * rest. The final app has options with TYPES and HELP TEXT, and a config
 * file, with a clear precedence:
 *
 *     built-in default  <  value in --config FILE  <  value on the command line
 *
 * rte_argparse parses the application part of argv (after "--"):
 *   -c, --config FILE        .ini file (rte_cfgfile)
 *   -b, --burst N            RX burst size (U16, checked 1..64 after parsing)
 *   -i, --stats-interval MS  stats period (U32)
 *   -k, --ka-ms MS           keepalive ping period (U32)
 *   -a, --stall-after S      simulate a hang after S seconds (U32, 0 = never)
 *   -t, --seconds S          run time when there is no shell (U32)
 *   --shell                  run the step 4 shell on the main lcore
 *   -h, --help               generated by rte_argparse
 *
 * app.ini sections: [forward] burst, pairN = rx,tx; [stats] interval_ms;
 * [keepalive] period_ms, stall_after.
 *
 * Everything else (the worker, the housekeeping service, keepalive, the
 * shell) is step 4 unchanged.
 *
 *   ./step5_options -l 0-2 -S 2 --no-pci --no-huge -m 128 --file-prefix=ch11-s5 \
 *       --vdev=net_ring0 --vdev=net_ring1 -- --config app.ini --burst 16
 */
