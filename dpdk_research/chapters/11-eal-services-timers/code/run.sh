#!/usr/bin/env bash
# SPDX-License-Identifier: BSD-3-Clause
# Chapter 11: build and run every step of the evolving app, the side demos,
# the exercise solutions and the related prebuilt DPDK samples.
# To refresh the captured output:
#     ./run.sh 2>&1 | tee expected_output.txt
#
# All runs: --no-pci, --no-huge -m 64..256 (no hugepages needed), a unique
# --file-prefix=ch11-*, timeout -s INT. Ports are net_ring loopback vdevs.
# Nothing touches eth0, no veth/tap/netns is created.
set -u
cd "$(dirname "$0")"

ENV_SH=${ENV_SH:-/tmp/claude-0/-home-user-ai-lab/fae9d2b5-bcbe-5be9-a4f0-08ae6c821ee6/scratchpad/dpdk-env.sh}
# shellcheck disable=SC1090
[ -f "$ENV_SH" ] && source "$ENV_SH"
E=$DPDK_SRC/build/examples
TMP=$(mktemp -d)
KA_SHM=/dev/shm/dpdk_keepalive_shm_name
[ -e "$KA_SHM" ] && KA_SHM_EXISTED=1 || KA_SHM_EXISTED=0

PREFIXES="ch11-s1 ch11-s2 ch11-s2ev ch11-s2old ch11-s2nol ch11-s3 ch11-s4 ch11-s5 ch11-alarm ch11-tool
          ch11-ex1 ch11-ex3 ch11-ex4 ch11-tmr ch11-svc ch11-ka ch11-js ch11-cmd"
cleanup() {
	for p in $PREFIXES; do
		rm -rf "/var/run/dpdk/$p" "/run/dpdk/$p"
		rm -f /dev/hugepages/"$p"map_* 2>/dev/null
	done
	# l2fwd-keepalive creates a POSIX shm segment for its monitoring agent
	[ "$KA_SHM_EXISTED" = 0 ] && rm -f "$KA_SHM"
	rm -rf "$TMP"
}
trap cleanup EXIT INT TERM

make -s all || { echo "build failed"; exit 1; }

# Clean captured text: strip ANSI colour codes and the CR that cmdline's
# line editor echoes after each command.
clean() { sed 's/\x1b\[[0-9;]*[A-Za-z]//g; s/\r$//; s/\r/\n/g'; }

report() {
	local rc=$1 secs=$2
	[ "$rc" -eq 124 ] && echo "[stopped by SIGINT from timeout after ${secs}s]"
	[ "$rc" -ne 0 ] && [ "$rc" -ne 124 ] && echo "[exit status $rc]"
	return 0
}

# run <secs> <binary> <args...>: print the command, run it bounded.
run() {
	local secs=$1 bin=$2; shift 2
	echo
	echo "\$ $bin $*" | sed "s#$E#\$E#"
	timeout -s INT -k 5 "$secs" stdbuf -oL "$bin" "$@" < /dev/null > "$TMP/out" 2>&1
	local rc=$?
	clean < "$TMP/out"
	report "$rc" "$secs"
}

# run_fed <secs> '<shell snippet producing stdin>' <binary> <args...>
run_fed() {
	local secs=$1 feed=$2 bin=$3; shift 3
	echo
	echo "\$ ($(echo "$feed" | tr -s '\n\t ' ' ')) | $bin $*" | sed "s#$E#\$E#"
	bash -c "$feed" | timeout -s INT -k 5 "$secs" stdbuf -oL "$bin" "$@" > "$TMP/out" 2>&1
	local rc=${PIPESTATUS[1]}
	clean < "$TMP/out"
	report "$rc" "$secs"
}

EAL1="--no-pci --no-huge -m 128 --vdev=net_ring0 --vdev=net_ring1"

echo "################ step 1: mini_l2fwd + rte_timer (one lcore)"
run 15 ./step1_timer -l 0 --file-prefix=ch11-s1 $EAL1

echo
echo "################ step 2: stats on a service lcore (-l 0,2 -S 2)"
run 15 ./step2_service -l 0,2 -S 2 --file-prefix=ch11-s2 $EAL1
echo
echo "# step 2 again with an event_sw vdev: a driver registers its own service"
run 15 ./step2_service -l 0,2 -S 2 --file-prefix=ch11-s2ev $EAL1 --vdev=event_sw0 -- --seconds 1
echo
echo "# step 2 with the deprecated -s <coremask> (first lines only)"
run 15 ./step2_service -l 0,2 -s 0x4 --file-prefix=ch11-s2old $EAL1 -- --seconds 1 | head -12
echo
echo "# step 2 with -S 2 but lcore 2 missing from -l (first lines only)"
run 15 ./step2_service -l 0-1 -S 2 --file-prefix=ch11-s2nol $EAL1 -- --seconds 1 | head -10

echo
echo "################ step 3: keepalive watchdog, the worker hangs after 3 s"
run 15 ./step3_keepalive -l 0-2 -S 2 --file-prefix=ch11-s3 $EAL1 -- --stall-after 3

echo
echo "################ step 4: a cmdline shell on the main lcore"
FEED4="sleep 1.2; echo 'show stats'; echo 'set burst 8'; sleep 1.1; echo 'show stats';
       echo 'set burst 999'; echo 'set burst 70000'; echo 'show keepalive'; echo stall;
       sleep 1.2; echo 'show keepalive'; echo bogus; echo help; echo quit"
run_fed 15 "$FEED4" ./step4_cli -l 0-2 -S 2 --file-prefix=ch11-s4 $EAL1

echo
echo "################ step 5: rte_argparse + rte_cfgfile"
echo "\$ cat app.ini"
cat app.ini
run 15 ./step5_options -l 0-2 -S 2 --file-prefix=ch11-s5 $EAL1 -- --config app.ini --burst 16
echo
echo "# step 5: keepalive settings from the command line, hang after 1 s"
run 15 ./step5_options -l 0-2 -S 2 --file-prefix=ch11-s5 $EAL1 -- \
	--config app.ini --ka-ms 100 --stall-after 1 --seconds 2
echo
echo "# step 5: the help text is generated by rte_argparse"
run 10 ./step5_options -l 0-2 -S 2 --file-prefix=ch11-s5 $EAL1 -- --help
echo
echo "# step 5: bad input"
run 10 ./step5_options -l 0-2 -S 2 --file-prefix=ch11-s5 $EAL1 -- --burst abc
run 10 ./step5_options -l 0-2 -S 2 --file-prefix=ch11-s5 $EAL1 -- --burst 200
run 10 ./step5_options -l 0-2 -S 2 --file-prefix=ch11-s5 $EAL1 -- --bogus
run 10 ./step5_options -l 0-2 -S 2 --file-prefix=ch11-s5 $EAL1 -- --config nope.ini
echo "\$ cat bad.ini"
cat bad.ini
run 10 ./step5_options -l 0-2 -S 2 --file-prefix=ch11-s5 $EAL1 -- --config bad.ini
echo
echo "# step 5 with the shell"
run_fed 15 "sleep 1.2; echo 'show stats'; echo quit" \
	./step5_options -l 0-2 -S 2 --file-prefix=ch11-s5 $EAL1 -- --config app.ini --shell

echo
echo "################ side demo: EAL alarms"
run 15 ./alarm_demo -l 0 --no-pci --no-huge -m 64 --file-prefix=ch11-alarm

echo
echo "################ appendix: the EAL toolbox"
run 25 ./toolbox -l 0 --no-pci --no-huge -m 64 --file-prefix=ch11-tool

echo
echo "################ exercise solutions"
run 15 ./ex1_timer_service -l 0,2 -S 2 --file-prefix=ch11-ex1 $EAL1
run 25 ./ex3_manage_cost -l 0 --no-pci --no-huge -m 128 --file-prefix=ch11-ex3
for b in 16 0 100 x; do
	run 10 ./ex4_burst_range -l 0 --no-pci --no-huge -m 64 --file-prefix=ch11-ex4 -- --burst $b
done

echo
echo "################ dpdk-cmdline-gen.py: generate the boilerplate from cmds.list"
echo "\$ cat cmds.list"
cat cmds.list
echo "\$ python3 \$DPDK_SRC/buildtools/dpdk-cmdline-gen.py cmds.list | head -40"
python3 -I "$DPDK_SRC/buildtools/dpdk-cmdline-gen.py" cmds.list | sed "s#$DPDK_SRC#\$DPDK_SRC#" | head -40

echo
echo "################ prebuilt samples"
run 4 "$E/dpdk-timer" -l 0-1 --no-pci --no-huge -m 64 --file-prefix=ch11-tmr
echo "# service_cores wants 6 lcores (5 service + main): with 4 it refuses its first profile"
run 3 "$E/dpdk-service_cores" -l 0-3 --no-pci --no-huge -m 64 --file-prefix=ch11-svc
run 5 "$E/dpdk-l2fwd-keepalive" -l 0-2 --no-pci --no-huge -m 256 --file-prefix=ch11-ka \
	--vdev=net_ring0 --vdev=net_ring1 -- -p 0x3 -K 100 -T 2
run 3 "$E/dpdk-l2fwd-jobstats" -l 0-1 --no-pci --no-huge -m 256 --file-prefix=ch11-js \
	--vdev=net_ring0 --vdev=net_ring1 -- -p 0x3 -q 2 -T 2
run_fed 6 "sleep 0.5; echo 'add obj1 10.11.0.1'; echo 'show obj1'; echo 'del obj1'; echo quit" \
	"$E/dpdk-cmdline" -l 0 --no-pci --no-huge -m 64 --file-prefix=ch11-cmd

echo
echo "################ done"
