"""Item response theory (2PL) and tinyBenchmarks-style efficient evaluation with 50 items.

Chapter 5, section 5.12 (#irt) and Figure 5.6.
Run:  python3 code/ch05/irt_tiny.py
Shows: 200 'training' mock models answer 1,000 items generated by a 2PL model
P(correct) = sigmoid(a_i (theta_l - b_i)). We fit a, b, theta by joint maximum likelihood (gradient
ascent in numpy), then estimate 100 new models' full-benchmark accuracy from only 50 items:
(a) a random 50-item subset, (b) 50 anchor items chosen by k-means on items' correctness vectors and
weighted by cluster size, (c) the IRT estimate: fit theta on the 50 items (random or anchors), predict all 1,000 items.
Items are sharp (median discrimination 3.3), i.e. a model's answers are fairly consistent.
"""
from __future__ import annotations

import numpy as np

N_TRAIN, N_ITEMS, N_TEST, BUDGET = 200, 1000, 100, 50


def sigmoid(x: np.ndarray) -> np.ndarray:
    return 1.0 / (1.0 + np.exp(-np.clip(x, -30, 30)))


def fit_2pl(y: np.ndarray, iters: int = 1500, lr: float = 0.05) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Joint MLE of theta (models), a (discrimination), b (difficulty) by gradient ascent."""
    n_m, n_i = y.shape
    theta = np.zeros(n_m)
    a = np.ones(n_i)
    b = -np.log(y.mean(axis=0).clip(0.02, 0.98) / (1 - y.mean(axis=0).clip(0.02, 0.98)))
    for _ in range(iters):
        r = y - sigmoid(a[None, :] * (theta[:, None] - b[None, :]))
        g_theta = (r * a[None, :]).sum(axis=1) / n_i
        g_a = (r * (theta[:, None] - b[None, :])).sum(axis=0) / n_m
        g_b = -(r * a[None, :]).sum(axis=0) / n_m
        theta += lr * 20 * g_theta
        a = np.clip(a + lr * g_a * 5, 0.05, 6.0)
        b += lr * g_b * 5
        mu, sd = theta.mean(), theta.std()
        theta = (theta - mu) / sd            # fix the scale: theta ~ (0, 1)
        b = (b - mu) / sd
        a = a * sd
    return theta, a, b


def fit_theta(resp: np.ndarray, a: np.ndarray, b: np.ndarray, iters: int = 200) -> float:
    """MAP ability for one model given fixed items (N(0,1) prior keeps all-correct finite)."""
    t = 0.0
    for _ in range(iters):
        p = sigmoid(a * (t - b))
        grad = (a * (resp - p)).sum() - t
        hess = -(a * a * p * (1 - p)).sum() - 1.0
        t -= grad / hess
    return t


def kmeans(x: np.ndarray, k: int, rng: np.random.Generator, iters: int = 50) -> tuple[np.ndarray, np.ndarray]:
    cent = x[rng.choice(len(x), k, replace=False)].astype(float)
    for _ in range(iters):
        d = ((x[:, None, :] - cent[None, :, :]) ** 2).sum(axis=2)
        lab = d.argmin(axis=1)
        for c in range(k):
            if (lab == c).any():
                cent[c] = x[lab == c].mean(axis=0)
    return lab, cent


def main() -> None:
    rng = np.random.default_rng(2402)
    a_true = rng.lognormal(1.2, 0.4, N_ITEMS)  # sharp items (median a = 3.3): LLM answers are fairly consistent
    b_true = rng.normal(0.0, 1.2, N_ITEMS)
    th_train = rng.normal(0, 1, N_TRAIN)
    th_test = rng.normal(0, 1, N_TEST)
    y_train = (rng.random((N_TRAIN, N_ITEMS)) < sigmoid(a_true * (th_train[:, None] - b_true))).astype(float)
    y_test = (rng.random((N_TEST, N_ITEMS)) < sigmoid(a_true * (th_test[:, None] - b_true))).astype(float)
    full = y_test.mean(axis=1)

    theta, a, b = fit_2pl(y_train)
    print(f"2PL fit on {N_TRAIN} models x {N_ITEMS} items: corr(a_hat, a) = {np.corrcoef(a, a_true)[0,1]:.3f}, "
          f"corr(b_hat, b) = {np.corrcoef(b, b_true)[0,1]:.3f}, corr(theta_hat, theta) = {np.corrcoef(theta, th_train)[0,1]:.3f}")
    assert np.corrcoef(b, b_true)[0, 1] > 0.95

    # anchors: k-means over items' correctness vectors across training models
    lab, cent = kmeans(y_train.T, BUDGET, np.random.default_rng(0))
    anchors, weights = [], []
    for c in range(BUDGET):
        members = np.nonzero(lab == c)[0]
        if len(members) == 0:
            continue
        d = ((y_train.T[members] - cent[c]) ** 2).sum(axis=1)
        anchors.append(members[d.argmin()])
        weights.append(len(members) / N_ITEMS)
    anchors, weights = np.array(anchors), np.array(weights)

    err_rand, err_anchor, err_irt, err_irt_rand = [], [], [], []
    rrng = np.random.default_rng(1)
    for m in range(N_TEST):
        sub = rrng.choice(N_ITEMS, BUDGET, replace=False)
        err_rand.append(abs(y_test[m, sub].mean() - full[m]))
        err_anchor.append(abs((weights * y_test[m, anchors]).sum() - full[m]))
        t = fit_theta(y_test[m, anchors], a[anchors], b[anchors])
        err_irt.append(abs(sigmoid(a * (t - b)).mean() - full[m]))
        t_r = fit_theta(y_test[m, sub], a[sub], b[sub])
        err_irt_rand.append(abs(sigmoid(a * (t_r - b)).mean() - full[m]))
    print(f"\nEstimating full {N_ITEMS}-item accuracy of {N_TEST} new models from {BUDGET} items (mean abs error, points):")
    rows = [(f"random {BUDGET} items", err_rand), (f"{len(anchors)} k-means anchors (weighted)", err_anchor),
            (f"IRT ability fit on random {BUDGET}", err_irt_rand), ("IRT ability fit on the anchors", err_irt)]
    for label, errs in rows:
        print(f"  {label:<34} {np.mean(errs)*100:5.2f}")
    assert np.mean(err_anchor) < np.mean(err_rand) and np.mean(err_irt) < np.mean(err_irt_rand) < np.mean(err_rand)

    print("\nFigure 5.6: item characteristic curves P(correct | theta) for three illustrative items")
    items = {"easy, flat (a=0.5, b=-1.0)": (0.5, -1.0), "medium (a=1.5, b=0.0)": (1.5, 0.0), "hard, sharp (a=3.0, b=1.5)": (3.0, 1.5)}
    grid = np.array([-3, -2, -1, 0, 1, 2, 3], dtype=float)
    print("  theta: " + " ".join(f"{g:5.1f}" for g in grid))
    for name, (ai, bi) in items.items():
        print(f"  {name:<27} " + " ".join(f"{v:5.2f}" for v in sigmoid(ai * (grid - bi))))


if __name__ == "__main__":
    main()
